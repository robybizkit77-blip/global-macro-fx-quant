'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../..');
const feed=JSON.parse(fs.readFileSync(path.join(root,'validation/fixtures/market_pulse_v25_observed_2026_11_10.json'),'utf8')).cross_asset;
// Archived five-asset snapshot; a rolling live source must not invalidate historical QA.
const {read}=require(path.join(root,'site/fx-quant-v2/next/risk-evidence-reading.js'));
const today='2026-11-10';
const actual=read(feed.streams,today);
assert(actual.ready,'Five-way matching histories exist');
assert.equal(actual.previousAsOf,'2026-11-04');
assert.equal(actual.asof,'2026-11-05');
assert.equal(actual.regime,'stress');
assert(actual.stale,'Nov 05 stress must not be marketed as a live Nov 10 regime');
assert.match(actual.headline,/storica/);
assert.match(actual.judgement,/credito/);
assert.match(actual.judgement,/non estendiamo questa diagnosi alla seduta di oggi/);
assert.match(actual.observation,/S&P 500/);
assert.match(actual.observation,/Nasdaq/);
assert.match(actual.observation,/VIX/);
assert.match(actual.observation,/credito HY/);
assert.match(actual.observation,/credito IG/);
const close=(a,b)=>Math.abs(a-b)<0.00001;
assert(close(actual.changes.SP500.change,-4.355658102494342));
assert(close(actual.changes.NASDAQCOM.change,-5.523320761051121));
assert(close(actual.changes.VIX.change,11.57));
assert(close(actual.changes.HY_OAS.change,16));
assert(close(actual.changes.IG_OAS.change,2));
assert.match(actual.sourceDates,/SP500 2026-11-05/);
assert.match(actual.sourceDates,/VIX 2026-11-09/);
assert.match(actual.sourceDates,/HY_OAS 2026-11-06/);
assert(!/undefined|NaN|Infinity/.test(JSON.stringify(actual)));
const empty=read({},today);
assert.equal(empty.ready,false);
assert.match(empty.headline,/Non abbiamo/);
const unavailable=structuredClone(feed.streams);
unavailable.VIX.history=unavailable.VIX.history.filter(x=>x[0]<'2026-11-01');
assert(read(unavailable,today).ready,'Past matching dates are still available and must be explicitly historical');
const missing=structuredClone(feed.streams);
missing.IG_OAS.history=[];
assert.equal(read(missing,today).ready,false,'No invented proxy when IG is missing');
const future=read(feed.streams,'2026-11-04');
assert.equal(future.ready,false,'A future-created source snapshot cannot be treated as point-in-time on an earlier date');
const mismatch=structuredClone(feed.streams);
mismatch.HY_OAS.history.push(['2026-11-05',99.9]);
assert.equal(read(mismatch,today).ready,false,'Duplicate date must fail closed');
const other=structuredClone(feed.streams);
other.SP500.history=other.SP500.history.filter(x=>x[0]!=='2026-11-05');
const otherRead=read(other,today);
assert(otherRead.ready);
assert(otherRead.asof<'2026-11-05','No mixed-day phantom sync');
const fixture=structuredClone(feed.streams);
for(const k of ['SP500','NASDAQCOM','VIX','HY_OAS','IG_OAS']){
 fixture[k].date='2026-11-05';
 fixture[k].history=fixture[k].history.filter(x=>x[0]<='2026-11-05');
}
const fresh=read(fixture,'2026-11-05');
assert(fresh.ready&&!fresh.stale);
assert.match(fresh.headline,/stress/i);
assert(!fresh.headline.includes('storica'),'Same-day case must be recognized as such');
const next='site/fx-quant-v2/next/';
const html=fs.readFileSync(path.join(root,next+'index.html'),'utf8');
const app=fs.readFileSync(path.join(root,next+'app.js'),'utf8');
assert(html.indexOf('risk-evidence-reading.js?v=23')<html.indexOf('app.js?v=18.'),'Risk evidence must load before versioned Next app');
assert(app.includes('risk-research-reading'),'Risk panel must render economic analysis');
assert(app.includes("route==='overview'||route==='pairs'||route==='cot'||route==='risk'"),'Old duplicate risk essay must be hidden');
assert(app.includes('Variazione dello spread'),'OAS displayed as bps, not OAS percent changes');
console.log('NEXT_RISK_V23_PASS: 5/5 real common-session Nov 04-05 observations, equity/VIX/HY/IG units, Nov 10 historical caveat, missing/future/duplicate guards.');
